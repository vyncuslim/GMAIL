import { extractEmail, migrateLegacyAddress, normalizeAddress } from "./mail-domains";

export type MailIdentity = {
  email: string;
  kind: "personal" | "company";
  displayName: string;
  imageSrc: string;
  imageAlt: string;
  website: string;
};

export type MailIdentitySettings = { personalPhotoUrl?: string };

const MAIL_ORIGIN = "https://mail.vyncuslim.com";

// The actual personal image URL comes from private server configuration and is
// never embedded in this source file. Reject credentials and control characters.
export function validatePhotoUrl(value: unknown): string {
  if (typeof value !== "string" || /[\u0000-\u001f\u007f]/.test(value)) return "";
  const raw = value.trim();
  if (!raw) return "";
  try {
    const url = new URL(raw);
    if (url.protocol !== "https:" || url.username || url.password) return "";
    return url.href;
  } catch {
    return "";
  }
}

// Only identities owned by this mailbox have images. For an address list, use
// its first valid address, never a later recipient that happens to match.
export function getMailIdentity(value: unknown, settings: MailIdentitySettings = {}): MailIdentity | null {
  const first = normalizeAddress(value)[0];
  if (!first) return null;
  const email = extractEmail(migrateLegacyAddress(first));
  const domain = email.split("@")[1];
  if (domain === "vynalthai.com" || domain === "mail.vynalthai.com") {
    return {
      email,
      kind: "company",
      displayName: "Vynalth AI",
      imageSrc: "/brand/vynalth-logo.png",
      imageAlt: "Vynalth AI logo",
      website: "https://vynalthai.com",
    };
  }
  if (domain === "vyncuslim.com" || domain === "mail.vyncuslim.com") {
    return {
      email,
      kind: "personal",
      displayName: "Vyncus Lim",
      imageSrc: validatePhotoUrl(settings.personalPhotoUrl),
      imageAlt: "Vyncus Lim portrait",
      website: "https://vyncuslim.com",
    };
  }
  return null;
}

// The API still authorizes the mailbox independently. Branding never grants
// permission to send. Existing display names are retained.
export function formatBrandedSender(from: string): string {
  if (/[\r\n]/.test(from)) return "";
  const raw = from.trim();
  const identity = getMailIdentity(raw);
  if (!identity) return raw;
  const wrapped = raw.match(/^((?:"(?:[^"\\]|\\.)*"|[^<>,;"]+)\s*)<[^<>]+>$/);
  if (wrapped?.[1].trim()) {
    // A legacy address changes domain while keeping the chosen display name.
    return raw.replace(/<[^<>]+>$/, `<${identity.email}>`);
  }
  return `${identity.displayName} <${identity.email}>`;
}

function escapeHtml(value: string): string {
  return value.replace(/[&<>"']/g, (character) => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;",
  })[character]!);
}

function textHtml(value: string): string {
  return `<div lang="und" dir="auto" style="white-space:pre-wrap;overflow-wrap:anywhere;line-height:1.6">${escapeHtml(value).replace(/\r\n?|\n/g, "<br />")}</div>`;
}

function signatureHtml(identity: MailIdentity): string {
  const image = identity.imageSrc.startsWith("/") ? MAIL_ORIGIN + identity.imageSrc : identity.imageSrc;
  const mailto = "mailto:" + encodeURIComponent(identity.email);
  const height = identity.kind === "personal" ? 70 : 56;
  const imageCell = image ? `<td style="padding:14px 14px 0 0;vertical-align:top"><img src="${escapeHtml(image)}" alt="${escapeHtml(identity.imageAlt)}" width="56" height="${height}" style="display:block;width:56px;height:${height}px;border-radius:8px;border:0" /></td>` : "";
  return `<table lang="en" dir="ltr" role="presentation" border="0" cellpadding="0" cellspacing="0" style="margin-top:20px;border-top:1px solid #e5e7eb;font-family:Arial,sans-serif;font-size:14px;color:#202124"><tbody><tr>${imageCell}<td style="padding-top:14px;vertical-align:top;line-height:1.6"><strong>${escapeHtml(identity.displayName)}</strong><br /><a href="${escapeHtml(mailto)}" style="color:#174ea6;text-decoration:none">${escapeHtml(identity.email)}</a><br /><a href="${escapeHtml(identity.website)}" style="color:#174ea6;text-decoration:none">${escapeHtml(identity.displayName)} website</a></td></tr></tbody></table>`;
}

function quoteBoundary(text: string): number {
  // Match the reply/forward separators generated by the composer. The entire
  // original suffix (including its blank lines) stays intact after the signature.
  const match = /(?:\r?\n){2}(?:On [^\r\n]+ wrote:\r?\n(?=>)|-{5,}[ \t]*Forwarded message[ \t]*-{5,}(?:\r?\n|$))/i.exec(text);
  return match?.index ?? text.length;
}

function appendToHtml(html: string, signature: string): string {
  // Preserve caller-authored HTML; insert only the trusted signature. For a full
  // document, keep it inside the existing body rather than after </html>.
  const closing = /<\/body\s*>/i.exec(html) || /<\/html\s*>/i.exec(html);
  const position = closing?.index ?? html.length;
  return html.slice(0, position) + signature + html.slice(position);
}

export function buildSignedMessage(input: { from: string; text: string; html?: string; personalPhotoUrl?: string }): { text: string; html?: string } {
  const identity = getMailIdentity(input.from, { personalPhotoUrl: input.personalPhotoUrl });
  if (!identity) return { text: input.text, html: input.html };
  const boundary = quoteBoundary(input.text);
  const original = input.text.slice(0, boundary);
  const quoted = input.text.slice(boundary);
  const textSignature = `-- \n${identity.displayName}\n${identity.email}\n${identity.website}`;
  const text = original + (original ? "\n\n" : "") + textSignature + quoted;
  const signature = signatureHtml(identity);
  if (input.html) return { text, html: appendToHtml(input.html, signature) };
  const content = textHtml(original) + signature + (quoted ? textHtml(quoted) : "");
  const html = `<!doctype html><html lang="und" dir="auto"><head><meta charset="utf-8" /><meta name="viewport" content="width=device-width, initial-scale=1" /><title>Email from ${escapeHtml(identity.displayName)}</title></head><body lang="und" dir="auto" style="margin:0;padding:16px;font-family:Arial,sans-serif;font-size:16px;color:#202124"><div lang="und" dir="auto">${content}</div></body></html>`;
  return { text, html };
}
